try:
    # Запрос количества элементов списка
    n = int(input("Введите количество элементов списка: "))
    # Создание списка
    m = []
    # Заполнение списка
    for i in range(n):
        print(f"Элемент: {i+1}")
        a = int(input("Введите элемент: "))
        m.append(a)
    # Копирование и сортировка списка
    b = sorted(m)
    # Проверка является ли отсортированным
    if b == m:
        print("Список отсортирован")
    else:
        print("Список не сортирован")
except ValueError:
    print("Это не число")
