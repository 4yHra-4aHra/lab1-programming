// Ввожу единственную библиотеку
#include <iostream>

int main() {
  // Спрашиваю у пользователя, какую фигуру он желает
  std::cout << "Что вы желаете?\n1.прямоугольник \n2.треугольник\n";
  char choice;
  std::cout << "3.елочку\n4.ромб\n!!!ВВЕДИТЕ ЦИФРУ!!!\n";
  std::cin >> choice;

  // Запрашиваю высоту нужной фигуры
  int N;
  std::cout << "Введите высоту фигуры: ";
  std::cin >> N;

  switch (choice) {
    case '1': {
      // Для прямоугольника необходима длина, запрашиваю её
      int M;
      std::cout << "Введите длину фигуры: ";
      std::cin >> M;
      std::cout << "\n";

      // Первый цикл для высоты, а второй для длины
      for (int i = 0; i < N; ++i) {
        for (int u = 0; u < M; ++u) {
          std::cout << "* ";
        }
        std::cout << "\n";
      }
      break;
    }
      // -----------------------------------------------------
    case '2': {
      std::cout << "\n";

      // Ввожу переменную "dlina" для того, чтобы количество звездочек в строке
      // увеличивалось
      int dlina = 1;
      for (int i = 0; i < N; ++i) {
        for (int u = 0; u < dlina; ++u) {
          std::cout << "* ";
        }
        dlina += 1;
        std::cout << "\n";
      }
      break;
    }
      // -----------------------------------------------------
    case '3': {
      std::cout << "\n";

      // Ввожу переменную "elb" для того, чтобы увеличить количество звездочек
      // в строке
      int elb = 1;
      for (int i = 0; i < N; ++i) {
        // Этот цикл для пробелов перед звездочками
        for (int u = N - i; u > 0; --u) {
          std::cout << ' ';
        }

        // Этот цикл выводит звездочки
        for (int u = 0; u < elb * 2 - 1; ++u) {
          std::cout << '*';
        }

        // Благодаря этому елочка похожа на елочку)))
        // т.е. это увеличивает количество звездочек на последующей строке на 2
        elb += 1;
        std::cout << "\n";
      }

      break;
    }
      // -----------------------------------------------------
    case '4': {
      // САМОЕ ТРУДНОЕ ДЛЯ ПОНИМАНИЯ
      std::cout << "\n";

      // Ввожу эту переменную для того, чтобы высота ромба соответствовала
      // необходимой высоте для пользователя
      int pol_romb = N / 2 + 1;
      // Аналогично с переменной "elb"
      int romb = 1;

      // Этот блок циклов создает первую половину ромба (Елочку, высота которой
      // меньше в 2 раза)
      for (int i = 0; i < N; ++i) {
        // Циклы аналогичные блоку циклов с Елочкой
        for (int u = N - i; u > 0; --u) {
          std::cout << ' ';
        }

        for (int u = 0; u < romb * 2 - 1; ++u) {
          std::cout << '*';
        }
        // Этот if прекращает работу внешнего цикла, если высота ромба дойдет
        // до половины
        if (i == pol_romb - 1) {
          std::cout << "\n";
          break;
        }

        romb += 1;

        std::cout << "\n";
      }

      // Второй блок циклов для второй половины ромба (перевернутой)
      // Эта переменная для того, чтобы количество звездочек уменьшалось
      int romb_2 = N / 2;
      // Эта переменная для того, чтобы количество пробелов увеличивалось
      int space = N / 2 + 1;

      for (int i = N + 1; i > 0; --i) {
        // Этот if для того, чтобы количество пробелов было таким, чтобы фигура
        // была похожа на ромб
        if (N % 2 == 0) {
          for (int u = space; u > 0; --u) {
            std::cout << ' ';
          }
        } else {
          for (int u = space + 1; u > 0; --u) {
            std::cout << ' ';
          }
        }
        space += 1;

        // Этот цикл выводит другую половину ромба в перевернутом виде
        for (int u = romb_2 * 2 - 1; u > 0; --u) {
          std::cout << '*';
        }
        // Этот if для того, чтобы убрать лишние пробелы после фигуры
        if (i == pol_romb + 1) {
          break;
        }

        // Для того, чтобы количество звездочек в последующей строке уменьшалось
        // на 2
        romb_2 -= 1;

        std::cout << "\n";
      }
      break;
    }

    // Для того, если пользователь ошибется
    default: {
      std::cout << "Вы ошиблись!";
    }
  }
  return 0;
}
