# Запрашиваю число на проверку
num = int(input('\nВведите число на проверку: '))

# Проверяю на четность
if num % 2 == 0:
    print('Четное')
else:
    print("Нечетное")

# Проверяю на крастность 3
if num % 3 == 0:
    print("\nЧисло делится на 3")
else:
    print("\nЧисло не делится на 3")

# Проверяю положительное ли число, отрицательное или 0
if num > 0:
    print("Положительное")
elif num < 0:
    print("Отрицательное")
else:
    print("Ноль")

